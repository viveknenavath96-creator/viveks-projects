import pandas as pd
import matplotlib.pyplot as plt
df = pd.read_csv("sales_data.csv")

# 1.Display first 5 records
print("First 5 records:")
print(df.head())

# 2. Total number of rows and columns
print(f"Total number of rows and columns: {df.shape}")

# 3. Check column names and data types
print(f"Column names: {df.columns.tolist()}")
print(f"Data types:\n{df.dtypes}")

# 4. Generate basic statistical information
print("Basic statistical information:")
print(df.describe())

# 5.Identify missing values in each column
print("Missing values in each column:")
print(df.isnull().sum())

# 6.Check missing values
print(df.isnull().sum())

# 7. Fill missing numerical values with column means
df["quantity"] = df["quantity"].fillna(df["quantity"].mean())
df["unit_price"] = df["unit_price"].fillna(df["unit_price"].mean())

# 8. Fill missing categorical value with mode
df["region"] = df["region"].fillna(df["region"].mode()[0])

# 9. Check duplicate records
print("Duplicates before cleaning:", df.duplicated().sum())

# 10. Remove duplicate records
df = df.drop_duplicates()

# 11. Verify missing values
print("\nMissing values after cleaning:")
print(df.isnull().sum())

# 12. Verify duplicates
print("\nDuplicates after cleaning:")
print(df.duplicated().sum())

# 13. Create a new column called total_sales
df["total_sales"]=df["quantity"]*df["unit_price"]

# 14.Calculate the total revenue generated from all transactions
print("\n Total revenue from transactions:")
print(df["total_sales"].sum())

# 15.Calculate the average sales value per transaction
print("\n The average sales:")
print(df["total_sales"].mean())

# 16.Find the highest-value transaction and identify its order ID
highest_index = df["total_sales"].idxmax()
print("\n The highest sales transactions:")
print(df.loc[highest_index,"order_id"])

# 17. Calculate the total quantity sold for each product
total_sold = df.groupby("product")["quantity"].sum()
print(f"\n The total quantity sold:{total_sold}")

# 18. Calculate total revenue for each product
each_product = df.groupby("product")["total_sales"].sum()
print(f"\n Total revenue for each product is: {each_product}")

# 19. Find the best-selling product by quantity
print(f"Best-selling product: {total_sold.idxmax()}")

# 20. Find the highest-revenue product
print(f"Highest-revenue product: {each_product.idxmax()}")

#21. Calculate the total revenue generated by each region
region_revenue = df.groupby("region")["total_sales"].sum()
print(f"\n Total revenue generated by each region: {region_revenue}")

# 22. Find the region with the highest revenue
print(f"Region with the highest revenue: {region_revenue.idxmax()}")

# 23.Find the lowest-revenue region
print(f"Region with the lowest revenue: {region_revenue.idxmin()}")

# 24. Calculate total revenue for each category
category_revenue = df.groupby("category")["total_sales"].sum()
print(f"\n Total revenue generated by each category: {category_revenue}")

# 25. Find the category generating the highest revenue
print(f"Category generating the highest revenue: {category_revenue.idxmax()}")

# 26. Find the lowest-revenue category
print(f"Category generating the lowest revenue: {category_revenue.idxmin()}")

# 27. Convert the date column into a proper datetime format
df["date"] = pd.to_datetime(df["date"])

#28. Extract the month from each transaction date
df["month"] = df["date"].dt.month

# 29. Calculate total revenue for each month
monthly_revenue = df.groupby("month")["total_sales"].sum()
print(f"\n Total revenue generated by each month: {monthly_revenue}")

# 30. Find the month with the highest revenue
print(f"Month with the highest revenue: {monthly_revenue.idxmax()}")

# 31. Find the month with the lowest revenue
print(f"Month with the lowest revenue: {monthly_revenue.idxmin()}")

# 32. Count the number of transactions for each payment method.
payment_method_counts = df.groupby("payment_method").size()

# 33. Calculate total revenue for each payment method
payment_method_revenue = df.groupby("payment_method")["total_sales"].sum()
print(f"\n Total revenue generated by each payment method: {payment_method_revenue}")

# 34. Find the highest-revenue payment method
print(f"Payment method generating the highest revenue: {payment_method_revenue.idxmax()}")

# 35. Find the lowest-revenue payment method
print(f"Payment method generating the lowest revenue: {payment_method_revenue.idxmin()}")

# 36. Product-wise revenue – Bar chart showing revenue generated by each product.
plt.figure(figsize=(10, 6))
plt.bar(each_product.index, each_product.values)
plt.title("Revenue Generated by Each Product")
plt.xlabel("Product")
plt.ylabel("Revenue")
plt.xticks(rotation=45)
plt.show()

# 37. Region-wise Revenue Create a bar chart showing how much revenue each region generated
plt.figure(figsize=(10, 6))
plt.bar(region_revenue.index, region_revenue.values)
plt.title("Revenue Generated by Each Region")
plt.xlabel("Region")
plt.ylabel("Revenue")
plt.xticks(rotation=45)
plt.show()

# 38. Monthly Revenue Trend This time, create a line chart instead of a bar chart
plt.figure(figsize=(10, 6))
plt.plot(monthly_revenue.index, monthly_revenue.values, marker='o')
plt.title("Monthly Revenue Trend")
plt.xlabel("Month")
plt.ylabel("Revenue")
plt.xticks(monthly_revenue.index)
plt.grid()
plt.show()

# 39. Category-wise Revenue ,Create a pie chart showing each category's contribution to total revenue
plt.figure(figsize=(8, 8))
plt.pie(category_revenue.values, labels=category_revenue.index, autopct='%1.1f%%', startangle=140)
plt.title("Category-wise Revenue Contribution")
plt.axis('equal')  # Equal aspect ratio ensures that pie is drawn as a circle.
plt.show()

