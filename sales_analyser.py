print(f"Best-selling product by quantity: {total_sold.idxmax()}")

# 44. Identify the product generating the highest revenue
print(f"Product generating the highest revenue: {each_product.idxmax()}")

# 45. Identify the region generating the highest revenue
print(f"Region generating the highest revenue: {region_revenue.idxmax()}")

# 46. Identify the category generating the highest revenue
print(f"Category generating the highest revenue: {category_revenue.idxmax()}")

# 47. Identify the month generating the highest revenue
print(f"Month generating the highest revenue: {monthly_revenue.idxmax()}")

# 48. Identify the payment method generating the highest revenue
print(f"Payment method generating the highest revenue: {payment_method_revenue.idxmax()}")

# 49. Save your cleaned dataset as a separate CSV
df.to_csv("cleaned_sales_data.csv", index=False)

